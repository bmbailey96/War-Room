import assert from 'node:assert/strict';
import {parseNewsRss,matchRosterNews,readNewsFeeds,NEWS_FEEDS} from '../netlify/functions/lib/news-v2.mjs';
const now=Date.parse('2026-10-28T12:00:00Z');
const item=(title,date=new Date(now-3600000).toUTCString(),url='https://example.com/story')=>`<item><title><![CDATA[${title}]]></title><link>${url}</link><pubDate>${date}</pubDate><description>Practice report for today</description></item>`;
const rss=body=>`<rss><channel>${body}</channel></rss>`;
const parsed=parseNewsRss(rss(item('DeVonta Smith &amp; A.J. Brown practice')+item('No date','')+item('Too old','Wed, 01 Jan 2025 12:00:00 GMT')+item('Future','Wed, 01 Jan 2031 12:00:00 GMT')+item('Unsafe',undefined,'javascript:alert(1)')),'CBS',now);
assert.equal(parsed.length,1);assert.equal(parsed[0].title,'DeVonta Smith & A.J. Brown practice');
assert.throws(()=>parseNewsRss('', 'CBS',now));
assert.throws(()=>parseNewsRss('<html>Access denied</html>', 'CBS',now));
const data={checkedAt:now,sources:[{name:'CBS',ok:true,lastSuccessAt:now,items:parsed}]};
assert.equal(matchRosterNews(data,[{name:'DeVonta Smith'}],now).items.length,1);
assert.equal(matchRosterNews(data,[{name:'Smith'}],now).items.length,0);
assert.equal(matchRosterNews(data,[{name:'John Smith'}],now).items.length,0);
assert.equal(matchRosterNews(data,[{name:'A.J. Brown'}],now).items.length,1);
assert.equal(matchRosterNews(data,[{name:'DeVonta Smith'}],now+73*3600000).items.length,0);
let saved=null,calls=0;
const cache={get:async()=>saved,setJSON:async(_,v)=>{saved=v}};
const success=async()=>{calls++;return {ok:true,text:async()=>rss(item('DeVonta Smith practices'))}};
await readNewsFeeds(cache,{fetcher:success,now});assert.equal(calls,NEWS_FEEDS.length);
await readNewsFeeds(cache,{fetcher:success,now:now+60000});assert.equal(calls,NEWS_FEEDS.length,'cache should avoid repeated feed calls');
const failed=await readNewsFeeds(cache,{fetcher:async()=>{throw Error('network')},now:now+16*60000});
const stale=matchRosterNews(failed,[{name:'DeVonta Smith'}],now+16*60000);
assert.equal(stale.available,false);assert.equal(stale.items.length,1);assert.equal(stale.items[0].stale,true);
assert.equal(stale.sources[0].lastSuccessAt,now);
const recovered=await readNewsFeeds(cache,{fetcher:success,now:now+19*60000});assert.equal(recovered.sources.every(s=>s.ok),true);
const mixed=await readNewsFeeds(cache,{now:now+40*60000,fetcher:async url=>url===NEWS_FEEDS[0].url?success():{ok:true,text:async()=>''}});
assert.equal(mixed.sources.filter(s=>s.ok).length,1);
assert.equal(matchRosterNews(mixed,[{name:'DeVonta Smith'}],now+40*60000).items[0].stale,false);
console.log('Public news checks passed: dates, safe links, roster isolation, cache, outages, partial feeds, and recovery.');
